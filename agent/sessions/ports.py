"""Persistence and lease operations used by session lifecycle policies."""

from __future__ import annotations

from typing import Any, Callable, Protocol
from datetime import datetime

from agent.sessions.contracts import SessionInfo
from agent.sessions.images import ImageAttachment, ImageAttachmentRef


class SessionLease(Protocol):
    @property
    def thread_id(self) -> str: ...
    def release(self) -> None: ...


class SessionRepository(Protocol):
    def get(self, session_id: str) -> SessionInfo | None: ...
    def resolve_prefix(self, prefix: str) -> SessionInfo | None: ...
    def list_sessions(self, *, limit: int = 50) -> list[SessionInfo]: ...
    def create_session(self, *, session_id: str | None = None, title: str = "",
                       model_id: str | None = None, permission_mode: str | None = None,
                       reasoning_effort: str = "default") -> SessionInfo: ...
    def try_acquire_session(self, thread_id: str) -> SessionLease | None: ...
    def wait_acquire_session(self, thread_id: str, *,
                             cancelled: Callable[[], bool] | None = None) -> SessionLease | None: ...
    def has_checkpoint(self, thread_id: str) -> bool: ...

    def turn_timings(self, session_id: str) -> dict[str, tuple[float, datetime]]: ...
    def model_metrics_history(self, session_id: str) -> list[dict[str, Any]]: ...


class ImageReader(Protocol):
    def read(self, ref: ImageAttachmentRef) -> ImageAttachment: ...
