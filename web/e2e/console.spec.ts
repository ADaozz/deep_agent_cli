test('model picker follows organization → model → effort and persists actual session selection', async ({ page, request }) => {
  await page.goto('/')
  const picker = page.getByRole('button', { name: '选择模型', exact: true })
  await expect(picker).toHaveText('model-one')
  const choose = async (source: string, model: string, effort: string) => {
    await picker.click()
    await expect(page.getByText('选择组织', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: source, exact: true }).click()
    await expect(page.getByText('选择模型名称', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: model, exact: true }).click()
    await expect(page.getByText('选择思考强度', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: effort, exact: true }).click()
    await expect(picker).toHaveText(model)
  }
  await choose('OrgB', 'model-three', 'high')
  await send(page, 'model-evidence')
  await answer(page, 'model=OrgB/model-three; effort=high')
  await choose('OrgA', 'model-two', '默认')
  await send(page, 'model-evidence')
  await answer(page, 'model=OrgA/model-two; effort=default')
  await page.reload()
  await expect(picker).toHaveText('model-two')
  await request.post('http://127.0.0.1:8766/restart/service')
  await page.reload()
  await expect(picker).toHaveText('model-two')
  await send(page, 'single')
  await expect(page.getByRole('region', { name: '工具审批' })).toBeVisible()
  await expect(picker).toBeDisabled()
  await approveSingle(page)
  await answer(page, 'single done')
  await expect(picker).toBeEnabled()
  await picker.click()
  await page.getByRole('button', { name: 'OrgA', exact: true }).click()
  await page.getByRole('button', { name: 'model-one', exact: true }).click()
  await page.screenshot({ path: path.resolve('../docs/frontend-evidence/console-model-effort-1440.png') })
})


