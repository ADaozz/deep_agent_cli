test('workspace picker remembers the last four paths and switches the actual workspace branch', async ({ page, request }) => {
  await page.goto('/')
  const list = await (await page.request.get('/api/agent/workspaces')).json()
  const paths = list.workspaces.map((item: {path: string}) => item.path)
  const choosePath = async (path: string) => {
    await page.getByRole('button', {name:'选择 workspace',exact:true}).click()
    await page.getByRole('button', {name:'选择路径…',exact:true}).click()
    const dialog = page.getByRole('dialog', {name:'选择 workspace 路径'})
    await expect(dialog).toBeVisible()
    await dialog.getByLabel('目录路径', {exact:true}).fill(path)
    await dialog.getByRole('button', {name:'选择此目录',exact:true}).click()
    await expect(dialog).toHaveCount(0)
    await expect(page.getByRole('button', {name:'选择 workspace',exact:true})).toHaveText(path)
  }
  for (const path of paths.slice(1)) await choosePath(path)
  // The fixture exposes two additional real sibling directories for selection.
  const parent = paths[0].slice(0, paths[0].lastIndexOf('/'))
  await choosePath(parent + '/extra-one')
  await choosePath(parent + '/extra-two')
  await page.getByRole('button', {name:'选择 workspace',exact:true}).click()
  const menu = page.locator('.popover')
  await expect(menu.locator('.pop-item')).toHaveCount(5)
  await expect(menu.locator('.pop-item').last()).toHaveText('选择路径…')
  await expect(menu.locator('.pop-item').first()).toContainText(parent + '/extra-two')
  await page.keyboard.press('Escape')
  await page.reload()
  await expect(page.getByRole('button', {name:'选择 workspace',exact:true})).toHaveText(parent + '/extra-two')
  await choosePath(paths[0])
  const branch = page.getByRole('button', {name:'选择 Git 分支',exact:true})
  await expect(branch).toHaveText('feature')
  await branch.click()
  await page.getByRole('button', {name:'main',exact:true}).click()
  await expect(branch).toHaveText('main')
  expect((await (await page.request.get('/api/agent/projects/app/git')).json()).branch).toBe('main')
  await send(page,'workspace branch test')
  await answer(page,'任务完成：workspace branch test')
  await page.getByRole('button', {name:'新对话',exact:true}).click()
  await page.getByRole('button', {name:'选择 workspace',exact:true}).click()
  await page.screenshot({path:path.resolve('../docs/frontend-evidence/console-workspace-picker-1440.png')})
  await page.keyboard.press('Escape')
  await request.post('http://127.0.0.1:8766/restart/service')
  const restored = await (await page.request.get('/api/agent/workspaces')).json()
  expect(restored.workspaces.some((item: {path: string}) => item.path === parent + '/extra-two')).toBe(true)
})
