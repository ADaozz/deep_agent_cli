import { test, expect, type Page } from '@playwright/test'
import path from 'node:path'

async function send(page: Page, text: string) {
  await page.getByLabel('向 Agent 输入指令').fill(text)
  await page.getByRole('button', { name: '发送', exact: true }).click()
}
async function approveSingle(page: Page) {
  await page.getByRole('button', { name: '批准 execute', exact: true }).click()
  await expect(page.getByRole('region', { name: '工具审批' })).toHaveCount(0)
}
async function answer(page: Page, text: string) {
  await expect(page.locator('.answer').last()).toContainText(text)
  await expect(page.getByRole('button', { name: '停止运行', exact: true })).toHaveCount(0)
}
